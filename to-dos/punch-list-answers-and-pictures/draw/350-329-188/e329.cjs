const { open, done } = require('../lib.cjs')
const R = require('./rows329.cjs')
async function printWindow(theme) {
  const p = await open({ as: 'assistant', theme, width: 1280, height: 1500, extra: R.extra })
  await p.go('/jobs?tab=materials')
  await p.getByRole('button', { name: /1321 · Cedar Bend/ }).click()
  await p.waitForTimeout(2000)
  await p.getByRole('button', { name: /Print future stickers/ }).first().click()
  await p.waitForTimeout(2000)
  const dlg = p.getByRole('dialog').last()
  await dlg.getByPlaceholder('G78, or G78-300').fill('G78-300')
  await dlg.getByRole('button', { name: 'Use the print window instead' }).click()
  await p.waitForTimeout(600)
  await dlg.locator('summary', { hasText: 'What the stickers will look like' }).click()
  await p.waitForTimeout(2500)
  if (theme === 'light') console.log('DLG\n' + (await dlg.innerText()).slice(0, 1500))
  await p.shot(`329-print-run-desk-${theme}.png`, { locator: dlg })
  await p.close2()
}
;(async () => {
  await printWindow('light')
  await printWindow('dark')
  const p = await open({ as: 'assistant', theme: 'light', width: 1280, height: 1000, extra: R.reserved })
  await p.go('/jobs?tab=materials')
  await p.getByRole('button', { name: /1321 · Cedar Bend/ }).click()
  await p.waitForTimeout(2500)
  await p.shot('329-reserved-line-desk-light.png', { clip: { x: 0, y: 110, width: 1280, height: 420 } })
  await p.getByRole('button', { name: /These are on boxes/ }).first().click()
  await p.waitForTimeout(1200)
  await p.getByLabel('Names').fill('G78-150')
  await p.getByRole('button', { name: 'Laydown yard' }).click()
  await p.waitForTimeout(800)
  await p.shot('329-these-are-on-boxes-desk-light.png', { clip: { x: 360, y: 160, width: 560, height: 700 } })
  console.log(JSON.stringify(await p.errs()).slice(0, 800))
  await p.close2(); await done()
})().catch((e) => { console.error(e); process.exit(1) })
