const { open, done } = require('../lib.cjs')
const { extra } = require('./bills.cjs')
const seal = require('./seal.cjs')
;(async () => {
  for (const theme of ['light', 'dark']) {
    const p = await open({ as: 'assistant', theme, width: 1280, height: 1000, extra: extra() }); await seal(p)
    await p.go('/materials?tab=parts-book')
    await p.getByRole('button', { name: 'Codes with no part' }).click()
    await p.waitForTimeout(2500)
    const dlg = p.locator('[role="dialog"]').last()
    const t = await dlg.innerText()
    console.log(theme, t.split('\n').filter((l) => /codes with no part ·|Match \d+|left for a person/.test(l)).join(' | '))
    await p.shot(`298-codes-with-no-part-desk-${theme}.png`, { locator: dlg })
    await p.close2()
  }
  let p = await open({ as: 'assistant', theme: 'light', width: 1280, height: 1000, extra: extra() }); await seal(p)
  await p.go('/materials?tab=what-we-buy')
  await p.shot('298-what-we-buy-desk-light.png', { clip: { x: 24, y: 100, width: 1232, height: 800 } })
  await p.getByText('3/4 Type L Hard Copper Tube 20ft').first().click()
  await p.waitForTimeout(2000)
  await p.shot('298-price-over-time-desk-light.png', { clip: { x: 24, y: 205, width: 1232, height: 705 } })
  await p.getByRole('button', { name: 'What to stock' }).or(p.getByRole('tab', { name: 'What to stock' })).first().click()
  await p.waitForTimeout(2000)
  await p.shot('298-what-to-stock-desk-light.png', { clip: { x: 24, y: 205, width: 1232, height: 700 } })
  console.log(JSON.stringify(await p.errs()).slice(0, 800))
  await p.close2(); await done()
})().catch((e) => { console.error(e); process.exit(1) })
