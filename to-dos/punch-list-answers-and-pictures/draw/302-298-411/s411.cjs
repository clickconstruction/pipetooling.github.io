const { open, done } = require('../lib.cjs')
const { extra } = require('./roll.cjs')
const seal = require('./seal.cjs')
;(async () => {
  let p = await open({ as: 'dev', theme: 'light', width: 1280, height: 1000, extra: extra('dev') }); await seal(p)
  await p.go('/prospects?tab=roll&roll=pulls')
  await p.shot('411-pulls-desk-light.png', { clip: { x: 24, y: 75, width: 1030, height: 685 } })
  await p.close2()
  for (const theme of ['light', 'dark']) {
    p = await open({ as: 'dev', theme, width: 1280, height: 1100, extra: extra('dev') }); await seal(p)
    await p.go('/prospects?tab=roll&roll=own')
    await p.shot(`411-our-own-desk-${theme}.png`, { clip: { x: 24, y: 75, width: 1030, height: 930 } })
    await p.close2()
  }
  p = await open({ as: 'dev', theme: 'light', width: 1280, height: 1330, extra: extra('dev') }); await seal(p)
  await p.go('/prospects?tab=roll&roll=everyone')
  await p.getByPlaceholder('Search a name or a license number').fill('sample')
  await p.waitForTimeout(1800)
  await p.locator('body').click({ position: { x: 1150, y: 500 } })
  await p.shot('411-everyone-desk-light.png', { clip: { x: 24, y: 75, width: 1030, height: 1170 } })
  await p.close2()
  p = await open({ as: 'dev', theme: 'light', width: 1280, height: 1000, extra: extra('dev') }); await seal(p)
  await p.go('/prospects?tab=roll&roll=everyone')
  await p.getByPlaceholder('Search a name or a license number').fill('sample')
  await p.waitForTimeout(1800)
  await p.getByText('Jordan Q. Sample').nth(1).click()
  await p.waitForTimeout(2000)
  const dlg = p.locator('[role="dialog"]').last()
  console.log('dialogs', await dlg.count())
  if (await dlg.count()) await p.shot('411-person-sheet-desk-light.png', { locator: dlg })
  else await p.shot('411-person-sheet-desk-light.png', { clip: { x: 322, y: 75, width: 636, height: 850 } })
  console.log(JSON.stringify(await p.errs()).slice(0, 800))
  await p.close2(); await done()
})().catch((e) => { console.error(e); process.exit(1) })
