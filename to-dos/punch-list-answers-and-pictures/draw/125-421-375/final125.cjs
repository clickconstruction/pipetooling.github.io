const { open, done } = require('../lib.cjs')
const { NOW, extra } = require('./world125.cjs')
async function row(theme) {
  const p = await open({ as: 'assistant', theme, width: 1440, height: 900, scale: 2, extra: extra() })
  await p.clock.install({ time: new Date(NOW) })
  await p.go('/jobs?tab=stages')
  const box = p.getByLabel('Job activity for Leak under slab').first()
  await box.scrollIntoViewIfNeeded()
  await box.hover()
  await p.waitForTimeout(1500)
  await p.mouse.move(5, 5)
  await p.waitForTimeout(300)
  const bb = await box.boundingBox()
  await p.shot(`125-row-box-desk-${theme}.png`, { clip: { x: 24, y: bb.y - 22, width: 1030, height: bb.height + 44 } })
  return p
}
;(async () => {
  let p = await row('light')
  // the expanded Job activity: Customer filter, Tie to this job, Reply
  const box = p.getByLabel('Job activity for Leak under slab').first()
  await p.setViewportSize({ width: 1440, height: 760 })
  await box.scrollIntoViewIfNeeded()
  await box.getByLabel('Expand job activity').click()
  await p.waitForTimeout(2000)
  await p.getByRole('tab', { name: /^Customer/ }).click()
  await p.waitForTimeout(600)
  await p.getByRole('button', { name: 'Reply to Sam’s text', exact: true }).click()
  await p.waitForTimeout(2500)
  const dlg = await p.getByRole('dialog').last().boundingBox()
  console.log('dlg', dlg)
  await p.shot('125-job-activity-reply-desk-light.png', { clip: { x: dlg.x - 6, y: dlg.y - 6, width: dlg.width + 12, height: dlg.height + 12 } })
  console.log(JSON.stringify(await p.errs()).slice(0, 800))
  await p.close2()
  p = await row('dark'); await p.close2()
  // the phone row's third line
  p = await open({ as: 'assistant', theme: 'light', width: 390, height: 844, phone: true, scale: 2, extra: extra() })
  await p.clock.install({ time: new Date(NOW) })
  await p.go('/jobs?tab=stages')
  await p.shot('125-phone-row-phone-light.png', { clip: { x: 0, y: 268, width: 390, height: 200 } })
  await p.close2(); await done()
})().catch((e) => { console.error(e); process.exit(1) })
