const { open, done } = require('../lib.cjs')
const { NOW, extra } = require('./world375.cjs')
const phone = (theme) => open({ as: 'primary', theme, width: 390, height: 844, phone: true, scale: 2, extra: extra() })
async function typing(theme, pick) {
  const p = await phone(theme)
  await p.clock.install({ time: new Date(NOW) })
  await p.go('/checklist?tab=today')
  await p.getByRole('button', { name: /2 notes/ }).first().click()
  await p.waitForTimeout(1200)
  const box = p.locator('textarea').first()
  await box.scrollIntoViewIfNeeded()
  await box.click()
  await p.keyboard.type('On my way to the shop. @', { delay: 40 })
  await p.waitForTimeout(600)
  await box.evaluate((el) => el.scrollIntoView({ block: 'center' }))
  await p.waitForTimeout(300)
  let bb = await box.boundingBox()
  await p.shot(`375-at-presses-phone-${theme}.png`, { clip: { x: 0, y: bb.y - 215, width: 390, height: 215 + bb.height + 75 } })
  if (pick) {
    await p.keyboard.type('ro', { delay: 60 })
    await p.waitForTimeout(400)
    await p.locator('[role=option]:has-text("gave this task"), button:has-text("gave this task")').first().tap()
    await p.waitForTimeout(400)
    await p.keyboard.type('is the charger with it?', { delay: 30 })
    await p.waitForTimeout(500)
    await box.evaluate((el) => el.scrollIntoView({ block: 'center' }))
    await p.waitForTimeout(300)
    bb = await box.boundingBox()
    await p.shot(`375-tag-marked-phone-${theme}.png`, { clip: { x: 0, y: bb.y - 250, width: 390, height: 250 + bb.height + 75 } })
  }
  await p.close2()
}
;(async () => {
  await typing('light', true)
  await typing('dark', false)
  let p = await phone('light')
  await p.clock.install({ time: new Date(NOW) })
  await p.go('/checklist?tab=today')
  await p.shot('375-today-tagged-phone-light.png', { clip: { x: 0, y: 0, width: 390, height: 760 } })
  await p.close2()
  p = await phone('light')
  await p.clock.install({ time: new Date(NOW) })
  await p.go('/dashboard')
  const line = p.getByText(/tagged you/).first()
  await line.evaluate((el) => el.scrollIntoView({ block: 'center' }))
  await p.waitForTimeout(400)
  const lb = await line.boundingBox()
  await p.shot('375-dashboard-needs-you-phone-light.png', { clip: { x: 0, y: lb.y - 125, width: 390, height: 400 } })
  await p.getByRole('button', { name: 'Open', exact: true }).first().click()
  await p.waitForTimeout(1500)
  await p.shot('375-needs-you-window-phone-light.png')
  console.log(JSON.stringify(await p.errs()).slice(0, 500))
  await p.close2(); await done()
})().catch((e) => { console.error(e); process.exit(1) })
