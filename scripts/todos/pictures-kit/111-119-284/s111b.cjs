const { open, done } = require('../lib.cjs')
const R = require('./rows.cjs')
;(async () => {
  const p = await open({ as: 'helpers', theme: 'light', width: 390, height: 844, phone: true, scale: 2, extra: { tables: { training_courses: R.courses, training_lesson_passes: R.lessonPasses(R.HAL, 'osha-30-refresher', 12), training_passes: [] } } })
  await p.go('/training/osha-30-refresher')
  console.log(await p.errs())
  await p.shot('111-lesson-phone-light.png')
  const check = p.locator('section[aria-label="Check yourself"]')
  const qs = check.locator('[data-question]')
  await qs.nth(0).getByText('Particulates', { exact: true }).click()
  await qs.nth(1).getByText('Inspect it for damage and cleanliness', { exact: true }).click()
  await p.waitForTimeout(300)
  const y = await check.evaluate((el) => el.getBoundingClientRect().top + window.scrollY)
  await p.evaluate((y) => window.scrollTo(0, y - 70), y)
  await p.waitForTimeout(500)
  console.log((await check.innerText()).replace(/\n+/g, ' / '))
  await p.shot('111-lesson-check-phone-light.png')
  console.log((await p.asks(/training/)).join('\n'))
  await p.close2(); await done()
})().catch((e) => { console.error(e); process.exit(1) })
