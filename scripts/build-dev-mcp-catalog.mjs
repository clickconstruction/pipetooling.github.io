#!/usr/bin/env node
// Generates supabase/functions/dev-mcp/catalog.ts from src/types/database.ts — the
// public schema's tables, views and RPCs, so a dev-mcp client (find_rpc / get_table)
// never guesses a name and the door can refuse one that does not exist — plus the
// edge functions' names (every supabase/functions/<name>/index.ts), which
// check_edge_boot probes.
//
//   node scripts/build-dev-mcp-catalog.mjs          # write the file
//   node scripts/build-dev-mcp-catalog.mjs --check  # exit 1 when the file is stale
//
// Run it after every `npm run gen-types:linked` and whenever an edge function is added,
// renamed or removed, then redeploy dev-mcp. A generated file: on a rebase conflict take
// main's database.ts and re-run this (CLAUDE.md).

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = 'src/types/database.ts'
const OUT = 'supabase/functions/dev-mcp/catalog.ts'
const FUNCTIONS_DIR = 'supabase/functions'
const RETURNS_MAX = 160

const source = ts.createSourceFile(SRC, readFileSync(join(root, SRC), 'utf8'), ts.ScriptTarget.ES2022, true)
const text = (node) => node.getText(source).replace(/\s+/g, ' ').trim()
const nameOf = (member) => (member.name ? member.name.getText(source).replace(/^["']|["']$/g, '') : '')
const members = (node) => (node && ts.isTypeLiteralNode(node) ? node.members.filter(ts.isPropertySignature) : [])
const child = (node, name) => members(node).find((m) => nameOf(m) === name)?.type

let database
source.forEachChild((node) => {
  if (ts.isTypeAliasDeclaration(node) && node.name.text === 'Database') database = node.type
})
if (!database) throw new Error(`${SRC}: no "export type Database"`)
const pub = child(database, 'public')
if (!pub) throw new Error(`${SRC}: Database has no "public" schema`)

function columnsOf(group, kind, into) {
  for (const t of members(child(pub, group))) {
    const columns = {}
    for (const c of members(child(t.type, 'Row'))) columns[nameOf(c)] = text(c.type)
    into[nameOf(t)] = { kind, columns }
  }
}
const tables = {}
columnsOf('Tables', 'table', tables)
columnsOf('Views', 'view', tables)

// An overloaded function is a union of { Args; Returns } literals.
const rpcs = {}
for (const f of members(child(pub, 'Functions'))) {
  const shapes = ts.isUnionTypeNode(f.type) ? f.type.types : [f.type]
  rpcs[nameOf(f)] = shapes.map((shape) => {
    const args = {}
    for (const a of members(child(shape, 'Args'))) args[nameOf(a) + (a.questionToken ? '?' : '')] = text(a.type)
    const ret = child(shape, 'Returns')
    const returns = ret ? text(ret) : 'unknown'
    return { args, returns: returns.length > RETURNS_MAX ? `${returns.slice(0, RETURNS_MAX)}…` : returns }
  })
}

const edgeFunctions = readdirSync(join(root, FUNCTIONS_DIR), { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_') && existsSync(join(root, FUNCTIONS_DIR, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort()

const sorted = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]))
const body =
  `// GENERATED by scripts/build-dev-mcp-catalog.mjs from ${SRC} and ${FUNCTIONS_DIR}/ — do not edit.\n` +
  `// Regenerate after gen-types or an edge-function add / rename / removal, then redeploy dev-mcp.\n\n` +
  `export type CatalogTable = { kind: 'table' | 'view'; columns: Record<string, string> }\n` +
  `export type CatalogRpc = { args: Record<string, string>; returns: string }\n\n` +
  `export const CATALOG_TABLES: Record<string, CatalogTable> = ${JSON.stringify(sorted(tables))}\n\n` +
  `export const CATALOG_RPCS: Record<string, CatalogRpc[]> = ${JSON.stringify(sorted(rpcs))}\n\n` +
  `export const EDGE_FUNCTIONS: string[] = ${JSON.stringify(edgeFunctions)}\n`

const outPath = join(root, OUT)
if (process.argv.includes('--check')) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : ''
  if (current !== body) {
    console.error(`${OUT} is stale — run: node scripts/build-dev-mcp-catalog.mjs`)
    process.exit(1)
  }
  console.log(`${OUT} is current (${Object.keys(tables).length} tables/views, ${Object.keys(rpcs).length} RPCs, ${edgeFunctions.length} edge functions)`)
} else {
  writeFileSync(outPath, body)
  console.log(`${OUT} written: ${Object.keys(tables).length} tables/views, ${Object.keys(rpcs).length} RPCs, ${edgeFunctions.length} edge functions, ${(body.length / 1024).toFixed(0)} KB`)
}
