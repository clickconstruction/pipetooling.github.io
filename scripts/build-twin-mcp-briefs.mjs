#!/usr/bin/env node
// Bundles the twin docs into supabase/functions/twin-mcp/briefs.ts (edge functions only
// deploy their own directory, so the markdown must ride the bundle). Regenerate after
// editing docs/twins/* and redeploy twin-mcp:  node scripts/build-twin-mcp-briefs.mjs
// Missions: only each mission's verbatim blockquote is embedded — twins never see the
// scorer's verification/scoring sections.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => readFileSync(join(root, p), 'utf8')

const brief = read('docs/twins/estimator.md')
const directory = read('docs/twins/APP_DIRECTORY.md')
const harnessPath = 'docs/twins/TWIN_HARNESS.md'
const harness = existsSync(join(root, harnessPath)) ? read(harnessPath) : ''
const ctGuidePath = 'docs/twins/COUNTTOOLING_BID_GUIDE.md'
const ctGuide = existsSync(join(root, ctGuidePath)) ? read(ctGuidePath) : ''
const ttGuidePath = 'docs/twins/TAKEOFFTOOLING_BID_GUIDE.md'
const ttGuide = existsSync(join(root, ttGuidePath)) ? read(ttGuidePath) : ''
// The pricing twin's brief (Price Matrix PR 3) — served by get_pricing_guide.
const pricingGuidePath = 'docs/twins/pricer.md'
const pricingGuide = existsSync(join(root, pricingGuidePath)) ? read(pricingGuidePath) : ''

// The placement/extraction protocol set rides the bundle too (owner ask 2026-08-30:
// a cloud twin without repo access must still read the doctrine). One string, three
// clearly-headed manuals: PLACEMENT.md (the engine manual) + its named siblings.
const placementDocs = ['docs/twins/PLACEMENT.md', 'docs/twins/CALIBRATION.md', 'docs/twins/EXTRACTOR.md']
const placementGuide = placementDocs
  .filter((d) => existsSync(join(root, d)))
  .map((d) => `<!-- ===== ${d} ===== -->\n\n${read(d)}`)
  .join('\n\n---\n\n')

// Extract each mission's verbatim text (the blockquote under "Mission text (verbatim):").
const missionsSrc = read('docs/twins/missions/estimator.md')
const missions = {}
const sections = missionsSrc.split(/^## /m).slice(1)
for (const sec of sections) {
  const idMatch = /^(M\d+)\s*·\s*([^\n(]+)/.exec(sec)
  if (!idMatch) continue
  const [, id, title] = idMatch
  const quote = /\*\*Mission text \(verbatim\):\*\*\n((?:>.*\n?)+)/.exec(sec)
  if (!quote) continue
  const text = quote[1].split('\n').map((l) => l.replace(/^>\s?/, '')).join('\n').trim()
  const prereq = /\*\*Prerequisites\*\*:\s*([^\n]+)/.exec(sec)
  missions[id] = { title: title.trim(), prerequisites: prereq ? prereq[1].trim() : '', text }
}

const out = `// GENERATED by scripts/build-twin-mcp-briefs.mjs — do not edit by hand.
// Source of truth: docs/twins/*. Regenerate + redeploy twin-mcp after editing them.
export const BRIEF: string = ${JSON.stringify(brief)}
export const DIRECTORY: string = ${JSON.stringify(directory)}
export const HARNESS: string = ${JSON.stringify(harness)}
export const CT_GUIDE: string = ${JSON.stringify(ctGuide)}
export const TT_GUIDE: string = ${JSON.stringify(ttGuide)}
export const PRICING_GUIDE: string = ${JSON.stringify(pricingGuide)}
export const PLACEMENT_GUIDE: string = ${JSON.stringify(placementGuide)}
export const MISSIONS: Record<string, { title: string; prerequisites: string; text: string }> = ${JSON.stringify(missions, null, 2)}
`
writeFileSync(join(root, 'supabase/functions/twin-mcp/briefs.ts'), out)

// The two Claude Desktop kickoffs ride into _shared for the twin-setup edge function
// (Price Matrix PR 6): a redeemed setup code hands the kickoff back with the connector
// URL filled in, so the person's clipboard holds the exact document the Console copies.
const desktopKickoff = read('docs/twins/kickoffs/desktop-operator.md')
const pricingKickoff = read('docs/twins/kickoffs/pricing-operator.md')
for (const [name, text] of [['desktop-operator', desktopKickoff], ['pricing-operator', pricingKickoff]]) {
  if (!text.includes('{{CONNECTOR_URL}}')) throw new Error(`docs/twins/kickoffs/${name}.md lost its {{CONNECTOR_URL}} placeholder`)
}
const kickoffsOut = `// GENERATED by scripts/build-twin-mcp-briefs.mjs — do not edit by hand.
// Source of truth: docs/twins/kickoffs/*.md. Regenerate + redeploy twin-setup after editing them.
export const KICKOFF_CONNECTOR_PLACEHOLDER = '{{CONNECTOR_URL}}'
export const DESKTOP_KICKOFF: string = ${JSON.stringify(desktopKickoff)}
export const PRICING_KICKOFF: string = ${JSON.stringify(pricingKickoff)}
`
writeFileSync(join(root, 'supabase/functions/_shared/twinKickoffs.ts'), kickoffsOut)
console.log(`briefs.ts written: brief ${brief.length}ch, directory ${directory.length}ch, harness ${harness.length}ch, pricing ${pricingGuide.length}ch, placement ${placementGuide.length}ch, missions ${Object.keys(missions).join(',') || '(none)'}`)
