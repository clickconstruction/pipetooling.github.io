import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { LIVE_SETTLE_MS, makeLiveBus } from './liveReread'

describe('the Messages live bus (v2.5572)', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())

  it('opens the channel for the first listener and closes it after the last', () => {
    const attach = vi.fn()
    const detach = vi.fn()
    const bus = makeLiveBus({ attach, detach })
    const offA = bus.subscribe(() => {})
    const offB = bus.subscribe(() => {})
    expect(attach).toHaveBeenCalledTimes(1)
    expect(bus.size).toBe(2)
    offA()
    expect(detach).not.toHaveBeenCalled()
    offB()
    offB()
    expect(detach).toHaveBeenCalledTimes(1)
    expect(bus.size).toBe(0)
    bus.subscribe(() => {})
    expect(attach).toHaveBeenCalledTimes(2)
  })

  it('settles a burst of bumps into one read for every listener', () => {
    const bus = makeLiveBus({ attach: () => {}, detach: () => {} })
    const a = vi.fn()
    const b = vi.fn()
    bus.subscribe(a)
    bus.subscribe(b)
    bus.bump()
    bus.bump()
    vi.advanceTimersByTime(LIVE_SETTLE_MS - 1)
    bus.bump()
    vi.advanceTimersByTime(LIVE_SETTLE_MS - 1)
    expect(a).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(a).toHaveBeenCalledTimes(1)
    expect(b).toHaveBeenCalledTimes(1)
  })

  it('fires at once on fire, drops a pending settle, and bumps nothing with nobody listening', () => {
    const bus = makeLiveBus({ attach: () => {}, detach: () => {}, settleMs: 50 })
    const a = vi.fn()
    bus.bump()
    vi.advanceTimersByTime(100)
    const off = bus.subscribe(a)
    bus.bump()
    bus.fire()
    expect(a).toHaveBeenCalledTimes(1)
    vi.advanceTimersByTime(100)
    expect(a).toHaveBeenCalledTimes(1)
    bus.bump()
    off()
    vi.advanceTimersByTime(100)
    expect(a).toHaveBeenCalledTimes(1)
  })
})
